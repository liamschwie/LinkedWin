// Reuse the tested page functions; omit the Frida/USB launchers from the tweak.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const games=[
 ['zip','Zip','__zipPlayer',['captureZipBoard','validateZipPuzzle','checkZipCells','replayZipDrag']],
 ['tango','Tango','__tangoPlayer',['readTangoContext','validateTangoPuzzle','tangoCellValue','replayTango']],
 ['queens','Queens','__queensPlayerV1',['readQueensContext','validateQueensPuzzle','queensCellValue','replayQueens']],
 ['mini-sudoku','MiniSudoku','__miniSudokuPlayerV3',['readMiniSudokuContext','parseMiniSudokuCells','solveMiniSudoku','replayMiniSudoku','observeMiniSudokuSaves']],
 ['patches','Patches','__patchesPlayerV1',['readPatchesContext','validatePatchesPuzzle','checkPatchesProgress','replayPatches','observePatchesSaves']],
 ['wend','Wend','__wendPlayerV1',['readWendContext','validateWendPuzzle','checkWendProgress','replayWend','observeWendSaves']],
 ['crossclimb','Crossclimb','__crossclimbPlayerV3',['captureCrossclimbPuzzle','readCrossclimbContext','validateCrossclimbPuzzle','fillCrossclimbRow','reorderCrossclimbRow','replayCrossclimb','observeCrossclimbSaves']],
 ['pinpoint','Pinpoint','__pinpointPlayerV1',['capturePinpointPuzzle','readPinpointContext','validatePinpointPuzzle','replayPinpoint','observePinpointSaves']]
];
const entries=games.map(([slug,name,key,helpers])=>{
 const runtime={};vm.runInNewContext(fs.readFileSync(path.join(root,'frida',slug+'-play.js'),'utf8'),runtime);
 const fn=id=>{if(typeof runtime[id]!=='function')throw Error('Missing '+id);return runtime[id].toString();};
 return JSON.stringify(slug)+':{key:'+JSON.stringify(key)+',install:action=>('+fn('install'+name+'Player')+')('+helpers.map(fn).join(',')+',action)}';
});
const source=`(()=>{
 if(window.__linkedWinTick)return;
 const games={${entries.join(',\n')}};
 let current=null,beganAt=Date.now(),playAt=null,started=false,stopped=false;
 window.__linkedWinStop=(discard=false)=>{if(current){const key=games[current].key;window[key]?.stop();if(discard){delete window[key];current=null;}}stopped=true;};
 window.addEventListener?.('pagehide',()=>window.__linkedWinStop(true));
 window.__linkedWinTick=()=>{
  const match=location.origin==='https://www.linkedin.com'&&/^\\/games\\/view\\/([a-z-]+)\\/?$/.exec(location.pathname);
  const game=match&&Object.hasOwn(games,match[1])?match[1]:null;
  if(game!==current){window.__linkedWinStop(true);current=game;beganAt=Date.now();playAt=null;started=false;stopped=false;}
  if(!game)return JSON.stringify({game:null,events:[]});
  if(document.hidden){if(!stopped)window.__linkedWinStop();return JSON.stringify({game,events:[]});}
  if(stopped)return JSON.stringify({game,events:[]});
  const entry=games[game];
  let result;
  if(game==='zip'){
   // Zip's Frida adapter is manual; readiness gates its single automatic start.
   result=entry.install('drain');const control=window[entry.key];
   if(!started){try{control.prepare();started=true;result=entry.install('play');}catch(_){}}
  }else result=window[entry.key]?.started?window[entry.key].drain():entry.install('auto');
  if((started||window[entry.key]?.started)&&playAt===null)playAt=Date.now();
  if(playAt===null?Date.now()-beganAt>60000:Date.now()-playAt>180000)window.__linkedWinStop();
  return JSON.stringify({...JSON.parse(result),game});
 };
})();`;
new vm.Script(source);
fs.mkdirSync(path.join(root,'generated'),{recursive:true});
fs.writeFileSync(path.join(root,'generated/players.js'),source);
fs.writeFileSync(path.join(root,'generated/Players.h'),'// Generated by scripts/bundle.cjs.\nstatic const unsigned char kPlayers[] = {\n'+Array.from(Buffer.from(source)).join(',')+',0\n};\n');
console.log('Bundled '+games.length+' tested game adapters ('+Buffer.byteLength(source)+' bytes).');
